func newWorkspace(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	write(t, filepath.Join(root, "go.work"), "go 1.27.0\n\nuse ./src/cli\n")
	write(t, filepath.Join(root, "src", "cli", "go.mod"), "module example.com/m/src/cli\n\ngo 1.27.0\n")
	for _, spec := range Specs(filepath.Join(root, "src", "cli")) {
		if err := os.MkdirAll(spec.Dir, 0o755); err != nil {
			t.Fatal(err)
		}
		write(t, filepath.Join(spec.Dir, spec.Lexer), "lexer grammar X;\n")
		write(t, filepath.Join(spec.Dir, spec.Parser), "parser grammar X;\n")
		for _, base := range spec.Bases {
			write(t, filepath.Join(spec.Dir, base), "package parser\n")
		}
	}
	return root
}

func newApp(t *testing.T, root string, runner exec.Runner) (App, *bytes.Buffer, *bytes.Buffer) {
	t.Helper()
	stdout, stderr := &bytes.Buffer{}, &bytes.Buffer{}
	app := App{
		Dir:     root,
		Runner:  runner,
		Stdout:  stdout,
		Stderr:  stderr,
		Home:    t.TempDir(),
		Fetcher: func(string) JarFetcher { return JarFetcher{Client: stubClient("jar"), URL: "http://antlr.test/jar"} },
	}
	return app, stdout, stderr
}

func stubClient(body string) *http.Client {
	return &http.Client{Transport: roundTripper(func(*http.Request) (*http.Response, error) {
		return &http.Response{
			StatusCode: http.StatusOK,
			Body:       io.NopCloser(strings.NewReader(body)),
			Header:     http.Header{},
		}, nil
	})}
}

type roundTripper func(*http.Request) (*http.Response, error)

func (f roundTripper) RoundTrip(r *http.Request) (*http.Response, error) { return f(r) }

