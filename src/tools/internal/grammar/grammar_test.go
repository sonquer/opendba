func TestJarFetcherDownloadsOnce(t *testing.T) {
	hits := 0
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		hits++
		w.Write([]byte("jar bytes"))
	}))
	defer server.Close()

	path := filepath.Join(t.TempDir(), "cache", "antlr.jar")
	fetcher := JarFetcher{Client: server.Client(), URL: server.URL}
	if err := fetcher.Ensure(context.Background(), path); err != nil {
		t.Fatalf("Ensure: %v", err)
	}
	if got := read(t, path); got != "jar bytes" {
		t.Errorf("jar content = %q", got)
	}
	if err := fetcher.Ensure(context.Background(), path); err != nil {
		t.Fatalf("second Ensure: %v", err)
	}
	if hits != 1 {
		t.Errorf("downloaded %d times, want 1", hits)
	}
}

