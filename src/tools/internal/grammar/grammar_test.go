type recordingRunner struct {
	calls  []string
	dirs   []string
	result exec.Result
	err    error
	emit   map[string]string
}

func (r *recordingRunner) Run(_ context.Context, dir string, name string, args ...string) (exec.Result, error) {
	r.calls = append(r.calls, exec.Format(name, args...))
	r.dirs = append(r.dirs, dir)
	for file, content := range r.emit {
		if err := os.WriteFile(filepath.Join(dir, file), []byte(content), 0o600); err != nil {
			return exec.Result{}, err
		}
	}
	return r.result, r.err
}

func newSpec(t *testing.T) Spec {
	t.Helper()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "XLexer.g4"), "lexer grammar X;\nA: {this.Push();};\n")
	write(t, filepath.Join(dir, "XParser.g4"), "parser grammar X;\nroot: {this.Check()}? A;\n")
	write(t, filepath.Join(dir, "x_lexer_base.go"), "package parser\n\nfunc Base() {}\n")
	write(t, filepath.Join(dir, "stale_parser.go"), "// Code generated by ANTLR. DO NOT EDIT.\npackage x\n")
	write(t, filepath.Join(dir, "keep.go"), "package x\n\nfunc Keep() {}\n")
	return Spec{
		Dialect: "x",
		Package: "xdialect",
		Dir:     dir,
		Lexer:   "XLexer.g4",
		Parser:  "XParser.g4",
		Bases:   []string{"x_lexer_base.go"},
	}
}

func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func read(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(data)
}

func TestGenerateInstallsOutput(t *testing.T) {
	spec := newSpec(t)
	runner := &recordingRunner{emit: map[string]string{
		"x_parser.go":   "// Code generated by ANTLR\npackage xdialect\n",
		"x_lexer.go":    "// Code generated by ANTLR\npackage xdialect\n",
		"XLexer.interp": "ignored",
	}}
	generator := Generator{Runner: runner, Jar: "/cache/antlr.jar"}

	written, err := generator.Generate(context.Background(), spec)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if len(written) != 2 {
		t.Fatalf("written = %v", written)
	}
	if _, err := os.Stat(filepath.Join(spec.Dir, "x_parser.go")); err != nil {
		t.Errorf("generated parser missing: %v", err)
	}
	if _, err := os.Stat(filepath.Join(spec.Dir, "stale_parser.go")); err == nil {
		t.Error("stale generated file must be removed")
	}
	if _, err := os.Stat(filepath.Join(spec.Dir, "keep.go")); err != nil {
		t.Error("hand written files must be kept")
	}
	if got := read(t, filepath.Join(spec.Dir, "x_lexer_base.go")); !strings.HasPrefix(got, "package xdialect") {
		t.Errorf("base package not rewritten: %q", got)
	}
	if _, err := os.Stat(filepath.Join(spec.Dir, "XLexer.interp")); err == nil {
		t.Error("interp files must not be installed")
	}

	command := runner.calls[0]
	for _, want := range []string{"java", "-jar /cache/antlr.jar", "-Dlanguage=Go", "-package xdialect", "-listener", "-no-visitor", "XLexer.g4", "XParser.g4"} {
		if !strings.Contains(command, want) {
			t.Errorf("command %q missing %q", command, want)
		}
	}
	if runner.dirs[0] == spec.Dir {
		t.Error("antlr must run in a staging directory, not in the vendored grammar directory")
	}
	if got := read(t, filepath.Join(spec.Dir, "XLexer.g4")); !strings.Contains(got, "this.") {
		t.Error("the vendored grammar must stay identical to upstream")
	}
}

