func TestAppFailures(t *testing.T) {
	t.Run("bad flag", func(t *testing.T) {
		app, _, _ := newApp(t, newWorkspace(t), &recordingRunner{})
		if code := app.Run(context.Background(), []string{"-nope"}); code != ExitUsage {
			t.Fatalf("exit = %d", code)
		}
	})
	t.Run("flag help", func(t *testing.T) {
		app, _, _ := newApp(t, newWorkspace(t), &recordingRunner{})
		if code := app.Run(context.Background(), []string{"-h"}); code != ExitOK {
			t.Fatalf("exit = %d", code)
		}
	})
	t.Run("no workspace", func(t *testing.T) {
		app, _, stderr := newApp(t, t.TempDir(), &recordingRunner{})
		if code := app.Run(context.Background(), nil); code != ExitFailure {
			t.Fatalf("exit = %d", code)
		}
		if !strings.Contains(stderr.String(), "no go.work") {
			t.Errorf("stderr = %q", stderr.String())
		}
	})
	t.Run("unknown module", func(t *testing.T) {
		app, _, stderr := newApp(t, newWorkspace(t), &recordingRunner{})
		if code := app.Run(context.Background(), []string{"-module", "nope"}); code != ExitUsage {
			t.Fatalf("exit = %d", code)
		}
		if !strings.Contains(stderr.String(), "unknown module") {
			t.Errorf("stderr = %q", stderr.String())
		}
	})
	t.Run("jar download fails", func(t *testing.T) {
		app, _, stderr := newApp(t, newWorkspace(t), &recordingRunner{})
		app.Fetcher = func(string) JarFetcher { return JarFetcher{URL: "http://127.0.0.1:1/jar"} }
		if code := app.Run(context.Background(), nil); code != ExitFailure {
			t.Fatalf("exit = %d", code)
		}
		if stderr.Len() == 0 {
			t.Error("the failure must be reported")
		}
	})
	t.Run("generation fails", func(t *testing.T) {
		app, _, stderr := newApp(t, newWorkspace(t), &recordingRunner{err: errors.New("java missing")})
		if code := app.Run(context.Background(), nil); code != ExitFailure {
			t.Fatalf("exit = %d", code)
		}
		if !strings.Contains(stderr.String(), "java missing") {
			t.Errorf("stderr = %q", stderr.String())
		}
	})
}

