func TestTransformRewritesReceivers(t *testing.T) {
	cases := []struct {
		name    string
		content string
		lexer   bool
		want    string
	}{
		{"lexer action", "{this.PushTag();}\n", true, "{l.PushTag();}\n"},
		{"lexer predicate", "{this.CheckLaMinus()}?\n", true, "{p.CheckLaMinus()}?\n"},
		{"parser action", "{this.Something();}\n", false, "{p.Something();}\n"},
		{"untouched", "SELECT: 'select';\n", true, "SELECT: 'select';\n"},
		{"repeated on one line", "{this.A(); this.B();}\n", true, "{l.A(); l.B();}\n"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := Transform(c.content, c.lexer); got != c.want {
				t.Errorf("Transform() = %q, want %q", got, c.want)
			}
		})
	}
}

