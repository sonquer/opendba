func TestFirstLineTruncates(t *testing.T) {
	long := "// " + string(make([]byte, 0))
	for i := 0; i < 100; i++ {
		long += "x"
	}
	got := []rune(firstLine(long))
	if len(got) != 73 {
		t.Errorf("len = %d, want 73: %q", len(got), string(got))
	}
	if got := firstLine("/* one\ntwo */"); got != "/* one …" {
		t.Errorf("multiline = %q", got)
	}
}

func TestScanDirectory(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "a.go"), []byte("package a\n\nfunc A() {\n\t// nope\n}\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	findings, err := Scan(dir)
	if err != nil {
		t.Fatalf("Scan: %v", err)
	}
	if len(findings) != 1 {
		t.Fatalf("got %v", findings)
	}
}

func TestScanRejectsNonDirectory(t *testing.T) {
	file := filepath.Join(t.TempDir(), "f.go")
	if err := os.WriteFile(file, []byte("package a\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := Scan(file); err == nil {
		t.Fatal("want error for file root")
	}
	if _, err := Scan(filepath.Join(t.TempDir(), "missing")); err == nil {
		t.Fatal("want error for missing root")
	}
}

func TestIsGenerated(t *testing.T) {
	cases := map[string]bool{
		"// Code generated from PostgreSQLParser.g4 by ANTLR 4.13.2. DO NOT EDIT.\n\npackage x\n": true,
		"// Code generated by mockgen. DO NOT EDIT.\npackage x\n":                                 true,
		"package x\n\n// Code generated later. DO NOT EDIT.\n":                                    false,
		"// a normal comment\npackage x\n":                                                        false,
		"package x\n":                                                                             false,
		"":                                                                                        false,
	}
	for source, want := range cases {
		if got := IsGenerated([]byte(source)); got != want {
			t.Errorf("IsGenerated(%q) = %v, want %v", source, got, want)
		}
	}
}

