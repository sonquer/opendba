func TestDocumentationCommentsAreAllowed(t *testing.T) {
	source := `// Package a documents the package.
package a

// Kind names a kind of thing.
type Kind int

const (
	// KindOne is the first kind.
	KindOne Kind = iota
)

// Config carries settings.
type Config struct {
	// Name is shown to the user.
	Name string
}

// Reader reads things.
type Reader interface {
	// Read reads one thing.
	Read() error
}

// Version is the current version.
var Version = "1"

// Run does the work.
func Run() {}
`
	findings, err := ScanFS(fstest.MapFS{"a.go": &fstest.MapFile{Data: []byte(source)}})
	if err != nil {
		t.Fatalf("ScanFS: %v", err)
	}
	if len(findings) != 0 {
		t.Fatalf("documentation comments must be allowed, got %v", findings)
	}
}

func TestCommentsInsideCodeAreRejected(t *testing.T) {
	source := `package a

// Run does the work.
func Run() int {
	// this explains a line
	value := 1
	return value // and this trails one
}

// a free floating comment

func Other() {}
`
	findings, err := ScanFS(fstest.MapFS{"a.go": &fstest.MapFile{Data: []byte(source)}})
	if err != nil {
		t.Fatalf("ScanFS: %v", err)
	}
	if len(findings) != 3 {
		t.Fatalf("got %d findings, want 3: %v", len(findings), findings)
	}
	for _, finding := range findings {
		if strings.Contains(finding.Text, "Run does the work") {
			t.Error("the documentation comment must not be reported")
		}
	}
}
