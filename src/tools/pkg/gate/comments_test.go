func TestIsDirective(t *testing.T) {
	cases := map[string]bool{
		"//go:build linux":       true,
		"//go:generate stringer": true,
		"//go:embed schema.json": true,
		"//line foo.go:1":        true,
		"// +build linux":        true,
		"// a normal comment":    false,
		"/* block */":            false,
		"//gopher":               false,
	}
	for text, want := range cases {
		if got := IsDirective(text); got != want {
			t.Errorf("IsDirective(%q) = %v, want %v", text, got, want)
		}
	}
}

func TestScanFSFindsComments(t *testing.T) {
	fsys := fstest.MapFS{
		"clean.go": &fstest.MapFile{Data: []byte("package a\n\nfunc F() int { return 1 }\n")},
		"dirty.go": &fstest.MapFile{Data: []byte("package a\n\nfunc G() int {\n\t// inside\n\treturn 2 // trailing\n}\n")},
		"build.go": &fstest.MapFile{Data: []byte("//go:build linux\n\npackage a\n")},
		"note.txt": &fstest.MapFile{Data: []byte("// not go\n")},
	}
	findings, err := ScanFS(fsys)
	if err != nil {
		t.Fatalf("ScanFS: %v", err)
	}
	if len(findings) != 2 {
		t.Fatalf("got %d findings, want 2: %v", len(findings), findings)
	}
	if findings[0].File != "dirty.go" || findings[0].Line != 4 {
		t.Errorf("first finding = %v, want dirty.go:4", findings[0])
	}
	if findings[1].Line != 5 {
		t.Errorf("second finding = %v, want line 5", findings[1])
	}
	if got := findings[0].String(); got != "dirty.go:4: // inside" {
		t.Errorf("String() = %q", got)
	}
}

func TestScanFSSkipsDirs(t *testing.T) {
	fsys := fstest.MapFS{
		"vendor/x/a.go":   &fstest.MapFile{Data: []byte("package x\n\nfunc A() {\n\t// vendored\n}\n")},
		"testdata/b.go":   &fstest.MapFile{Data: []byte("package x\n\nfunc B() {\n\t// fixture\n}\n")},
		".hidden/c.go":    &fstest.MapFile{Data: []byte("package x\n\nfunc C() {\n\t// hidden\n}\n")},
		"internal/ok.go":  &fstest.MapFile{Data: []byte("package x\n\nfunc D() {}\n")},
		"internal/bad.go": &fstest.MapFile{Data: []byte("package x\n\nfunc E() {\n\t/* block */\n}\n")},
	}
	findings, err := ScanFS(fsys)
	if err != nil {
		t.Fatalf("ScanFS: %v", err)
	}
	if len(findings) != 1 || findings[0].File != "internal/bad.go" {
		t.Fatalf("got %v, want only internal/bad.go", findings)
	}
}

